const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const LOCK_PATH = path.join(ROOT, "assets", "external", "asset-lock.json");
const OUT_PATH = path.join(ROOT, "js", "asset-data.js");

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, "utf8"));
}

function mimeFor(filePath) {
  const ext = path.extname(filePath).toLowerCase();
  if (ext === ".png") return "image/png";
  if (ext === ".jpg" || ext === ".jpeg") return "image/jpeg";
  if (ext === ".webp") return "image/webp";
  return null;
}

const lock = readJson(LOCK_PATH);
const data = {};

for (const asset of lock.downloads || []) {
  const localPath = path.join(ROOT, asset.localPath);
  const mime = mimeFor(localPath);
  if (!mime || !fs.existsSync(localPath)) continue;
  const externalPath = asset.localPath.replace(/^assets\/external\//, "");
  const bytes = fs.readFileSync(localPath);
  data[externalPath] = `data:${mime};base64,${bytes.toString("base64")}`;
}

const body = [
  "// Generated by scripts/build-external-asset-data.js. Do not edit manually.",
  "window.ML = window.ML || {};",
  `window.ML.EXTERNAL_ASSET_DATA = Object.freeze(${JSON.stringify(data, null, 2)});`,
  ""
].join("\n");

fs.writeFileSync(OUT_PATH, body);
console.log(JSON.stringify({
  output: path.relative(ROOT, OUT_PATH).replace(/\\/g, "/"),
  assets: Object.keys(data).length,
  bytes: Buffer.byteLength(body)
}, null, 2));
